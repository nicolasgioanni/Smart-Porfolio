// @vitest-environment node
import { mkdtemp, mkdir, readFile, rm, symlink, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { parseContentVersion, releaseProducerForEnvironment, writeContentVersion } from "../writeContentVersion.mjs";
import { assertAcceptedSnapshot, compilePagesFunctions, parseGeneration, validateGeneratedSource } from "./lifecycle.mjs";

const temporaryDirectories = [];
const generated = {
  metadata: {
    contentHash: "a".repeat(64), sourceMode: "templates",
    sources: Object.fromEntries(["profile", "links", "research", "projects", "experience", "recommendations", "education", "skills", "site_settings", "resume"].map((sheet) => [sheet, "template"]))
  }
};

afterEach(async () => Promise.all(temporaryDirectories.splice(0).map((directory) => rm(directory, { force: true, recursive: true }))));

describe("bounded release stages", () => {
  it.each([null, "index.js", "config.json", "routes.json"])("admits only regular compiled bytes before copying them (%s)", async (linkedFile) => {
    const root = await mkdtemp(path.join(os.tmpdir(), "release-compile-test-")); temporaryDirectories.push(root);
    const out = path.join(root, "out");
    await mkdir(out); await mkdir(path.join(root, "public"));
    const routes = { version: 1, include: ["/api/contact", "/api/contact/verify"], exclude: [] };
    await writeFile(path.join(root, "public", "_routes.json"), JSON.stringify(routes));
    await writeFile(path.join(out, "_routes.json"), JSON.stringify(routes));
    const worker = "export default { fetch() { return new Response('fixture'); } };";
    const files = {
      "index.js": worker,
      "config.json": JSON.stringify({ baseURL: "/", routes: routes.include.map((routePath) => ({ routePath, method: "", module: ["fixture.ts"] })) }),
      "routes.json": JSON.stringify(routes)
    };
    const commandRunner = async (_command, args) => {
      const temporary = args[args.indexOf("--outdir") + 1];
      for (const [name, content] of Object.entries(files)) {
        if (name === linkedFile) {
          const external = path.join(root, "linked-source"); await writeFile(external, content);
          await symlink(external, path.join(temporary, name));
        } else await writeFile(path.join(temporary, name), content);
      }
    };
    const build = compilePagesFunctions({ projectRoot: root, outDirectory: out, compatibilityDate: "2026-10-01", commandRunner });
    if (linkedFile) {
      await expect(build).rejects.toThrow();
      await expect(readFile(path.join(out, "_worker.js"))).rejects.toMatchObject({ code: "ENOENT" });
    } else {
      await build;
      expect(await readFile(path.join(out, "_worker.js"), "utf8")).toBe(worker);
      expect(await readFile(path.join(out, "_routes.json"), "utf8")).toBe(files["routes.json"]);
    }
  });

  it("accepts only the declared generated bytes and matching target source mode", async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), "release-snapshot-test-"));
    temporaryDirectories.push(root);
    const generatedPath = path.join(root, "src", "content", "generated", "portfolio.generated.json");
    await mkdir(path.dirname(generatedPath), { recursive: true });
    const bytes = Buffer.from(`${JSON.stringify(generated)}\n`);
    await writeFile(generatedPath, bytes);
    const digest = (await import("node:crypto")).createHash("sha256").update(bytes).digest("hex");
    await expect(assertAcceptedSnapshot({ projectRoot: root, snapshotDigest: digest, target: "local" })).resolves.toMatchObject({ sourceMode: "templates", snapshotDigest: digest });
    await expect(assertAcceptedSnapshot({ projectRoot: root, snapshotDigest: "b".repeat(64), target: "local" })).rejects.toThrow("do not match");
    expect(validateGeneratedSource(generated, "local")).toBe("templates");
  });

  it("keeps existing build callers on legacy metadata until they declare a sealed identity", async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), "release-version-test-"));
    temporaryDirectories.push(root);
    const generatedContentPath = path.join(root, "generated.json");
    await writeFile(generatedContentPath, JSON.stringify({ metadata: {
      contentHash: "a".repeat(64), generatedAt: "2026-10-12T00:00:00.000Z"
    } }));
    const version = await writeContentVersion({ generatedContentPath,
      outputPath: path.join(root, "content-version.json"),
      environment: { DEPLOYMENT_COMMIT_SHA: "b".repeat(40) },
      now: () => "2026-10-12T00:00:00.000Z"
    });
    expect(version.schemaVersion).toBe(1);
    expect(version).not.toHaveProperty("target");
    expect(version).not.toHaveProperty("producer");
  });

  it("records Actions provenance for non-deployable PR candidates without inventing an offline producer", () => {
    const producer = releaseProducerForEnvironment("local", {
      RELEASE_RUN_ID: "701", RELEASE_RUN_NUMBER: "42", RELEASE_PRODUCER_ATTEMPT: "3"
    });
    expect(producer).toEqual({ kind: "github-actions", runId: "701", runNumber: 42, attempt: 3 });
    expect(parseContentVersion({ schemaVersion: 2, commitSha: "b".repeat(40), contentHash: "a".repeat(64),
      generatedAt: "2026-10-12T00:00:00.000Z", deployedAt: "2026-10-12T00:00:00.000Z",
      target: "local", publicBuildInputDigest: "c".repeat(64), producer }).target).toBe("local");
    expect(() => releaseProducerForEnvironment("local", { RELEASE_RUN_ID: "701" })).toThrow();
    expect(() => releaseProducerForEnvironment("production", {})).toThrow();
  });

  it("marks local generation explicitly and refuses fabricated deployable generations", () => {
    expect(parseGeneration("local", "local")).toEqual({ kind: "local", runId: "local", runNumber: null, attempt: null });
    expect(parseGeneration("701:42:3", "production")).toEqual({ kind: "github-actions", runId: "701", runNumber: 42, attempt: 3 });
    expect(parseGeneration("701:42:3", "local")).toEqual({ kind: "github-actions", runId: "701", runNumber: 42, attempt: 3 });
    expect(() => parseGeneration("local", "preview")).toThrow("Only local");
    expect(() => parseGeneration("701:0:1", "preview")).toThrow("invalid");
  });
});
